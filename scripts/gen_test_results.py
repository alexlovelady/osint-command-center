"""Run the automation acceptance tests and write docs/test-results.md: every AUT-xx criterion, the tests that cover it, and what ran, skipped or failed.

    uv run python scripts/gen_test_results.py

Nothing is hand-written: results come from pytest's JUnit output, with the tool versions of this machine.
"""
from __future__ import annotations

import platform
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from osintcc import __version__

CRITERIA = {
    "AUT-01": ("All 30 template definitions load and pass schema/fixture validation", ["30_catalog", "every_template", "registry_and_handlers", "watch_templates", "template_library"]),
    "AUT-02": ("Missing tool/API/key is shown accurately; no fake results", ["missing_key", "template_library"]),
    "AUT-03": ("AI builds a valid typed workflow or returns an actionable error", ["ai_builds", "ai_correction", "closest_template", "explain_is_derived"]),
    "AUT-04": ("AI cannot produce script/shell/SQL nodes", ["ai_cannot_produce"]),
    "AUT-05": ("Visual edits round-trip without changing semantics", ["draft_edits_round_trip"]),
    "AUT-06": ("Scope, redirect, expired authorization, discovered-target tests fail closed", ["private_and_local", "scope_check", "enrich_rechecks", "active_mode"]),
    "AUT-07": ("Activation cannot bypass approval; drafts never schedule themselves", ["drafts_never_schedule", "expired_or_revoked"]),
    "AUT-08": ("Scheduler: IANA time zones, DST, missed-run policy", ["cron_", "missed_run", "trigger_slot"]),
    "AUT-09": ("Crash/restart reconstructs jobs without duplicate notifications", ["restart_"]),
    "AUT-10": ("Cancellation propagates; no orphan workers", ["cancel_stops"]),
    "AUT-11": ("Bounded retries, honour quotas", ["transient_failures", "request_budget"]),
    "AUT-12": ("Snapshot comparison: added/removed/changed/uncertain with provenance", ["snapshot_comparison", "partial_dataset", "two_real_runs"]),
    "AUT-13": ("One deduplicated notification per window", ["notification_dedupe", "notification_inbox"]),
    "AUT-14": ("Case exports include workflow/version/run metadata", ["case_reports_cite"]),
    "AUT-15": ("Offline use: local data, templates and editor work; network jobs pause", ["offline_pauses", "skips_network_triggers"]),
    "AUT-16": ("Cloud AI gets no case evidence without provider-specific opt-in", ["cloud_ai_needs"]),
    "AUT-17": ("Secrets never enter YAML, logs, chat or exports", ["secrets_never"]),
    "AUT-18": ("Suggestions off by default; dismissible", ["suggestions_are_off"]),
    "AUT-19": ("Windows/Linux run identical core fixture tests", ["identical_results_on_every_platform"]),
    "AUT-20": ("Restore an encrypted backup and rebuild workflows, approvals, history, reports without secrets", ["backup_restore"]),
    "AUT-21": ("Changing an active workflow makes an immutable version and re-evaluates approval", ["new_immutable_version"]),
    "AUT-22": ("Error recovery gives real diagnostics; AI never claims success", ["failed_runs_are_diagnosed"]),
    "AUT-23": ("Runs auditable: digests, timestamps, errors, evidence refs", ["case_reports_cite", "run_console"]),
    "AUT-24": ("Accessible keyboard navigation, labels, contrast (browser tests, see apps/web/e2e/automations.spec.ts)", []),
}


def main() -> int:
    with tempfile.TemporaryDirectory() as td:
        xml = Path(td) / "r.xml"
        subprocess.run([sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", f"--junitxml={xml}", "tests/integration/test_automations.py",
                        "tests/integration/test_automations_2.py", "tests/integration/test_automations_3.py"], cwd=ROOT, check=False, capture_output=True)
        root = ET.parse(xml).getroot()
    cases = []
    for tc in root.iter("testcase"):
        state = "failed" if tc.find("failure") is not None or tc.find("error") is not None else "skipped" if tc.find("skipped") is not None else "passed"
        reason = (tc.find("skipped").get("message") if tc.find("skipped") is not None else "") or ""
        cases.append((tc.get("name", ""), state, reason))
    L = ["# Automation test results", "",
         f"Generated by `scripts/gen_test_results.py` on {platform.platform()}, Python {platform.python_version()}, application {__version__}. Network is mocked in these tests; live runs are listed in `docs/progress.md`.", "",
         f"Total: **{len(cases)}** tests, {sum(1 for c in cases if c[1] == 'passed')} passed, {sum(1 for c in cases if c[1] == 'failed')} failed, {sum(1 for c in cases if c[1] == 'skipped')} skipped.", "",
         "| Criterion | Requirement | Tests | Result |", "|---|---|---|---|"]
    for k, (desc, pats) in CRITERIA.items():
        hit = [c for c in cases if any(p in c[0] for p in pats)]
        res = "browser tests" if not pats else ("**FAILED**" if any(c[1] == "failed" for c in hit) else "no test found" if not hit else f"{sum(1 for c in hit if c[1] == 'passed')}/{len(hit)} passed" + (f", {sum(1 for c in hit if c[1] == 'skipped')} skipped" if any(c[1] == 'skipped' for c in hit) else ""))
        L.append(f"| {k} | {desc} | {len(hit)} | {res} |")
    skipped = [c for c in cases if c[1] == "skipped"]
    L += ["", "## Skipped tests", ""] + ([f"- `{n}`: {r}" for n, _, r in skipped] or ["None."])
    (ROOT / "docs" / "test-results.md").write_text("\n".join(L) + "\n", encoding="utf8")
    bad = [c for c in cases if c[1] == "failed"]
    print(f"{len(cases)} tests, {len(bad)} failed")
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
