"""Write docs/source-capability-matrix.md from the running registry: which source takes which input, what it needs, how it was tested, and what it is NOT.

    uv run python scripts/gen_source_matrix.py
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from osintcc.profile.registry import SOURCES

TEST = {"live_tested": "Live-tested", "mocked_only": "Fixture-tested only (not proven against the live service)", "partially_verified": "Partly verified", "manual": "Manual (a person enters it)"}


def main() -> None:
    rows = ["# Source capability matrix", "",
            "Generated by `scripts/gen_source_matrix.py` from the source registry. \"Fixture-tested\" means checked against recorded or synthetic responses through a mock transport; "
            "it is **not** a claim that the live service was exercised. A source that is installed but has no key, or is not authorized for the subject, does not run; the investigation says so.", "",
            "| Source | Takes | Consent class | Privacy | Testing | Sends the input to |", "|---|---|---|---|---|---|"]
    for s in sorted(SOURCES.values(), key=lambda x: (x.category, x.id)):
        kinds = ", ".join(s.identifier_kinds) or "(manual entry)"
        rows.append(f"| {s.label} (`{s.id}`) | {kinds} | {s.source_class} | {s.privacy.replace('_', ' ')} | {TEST.get(s.maturity, s.maturity)} | "
                    f"{'nothing (local)' if s.manual else 'a third-party site, after your approval' if s.source_class == 'public_site_query' else 'a public registry or API'} |")
    rows += ["", "**Inputs with no automatic source:** a phone number (stored masked; no approved phone-discovery source exists) and a name alone (no configured source searches by name).",
             "**Never done:** password-reset or login probing, credential testing, face recognition, covert scanning, purchase of restricted or breach data, or research from a handle you have not confirmed."]
    (ROOT / "docs" / "source-capability-matrix.md").write_text("\n".join(rows) + "\n", encoding="utf-8")
    print("wrote docs/source-capability-matrix.md")


main()
