"""Generate docs/automation-capabilities.md (node registry, template catalog and what each template needs) from the code.

    uv run python scripts/gen_automation_docs.py [--check]
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from osintcc.adapters.registry import default_adapters
from osintcc.automations import catalog, handlers
from osintcc.automations.registry import ERROR_CODES, HANDLERS, SPECS

OUT = ROOT / "docs" / "automation-capabilities.md"


def build() -> str:
    ads = default_adapters()
    assert set(SPECS) == set(HANDLERS) and handlers.Ctx
    L = ["# Automation capability matrix", "",
         "Generated by `scripts/gen_automation_docs.py` from the node registry, the adapter registry and the bundled template files. Do not edit by hand.", "",
         "## Node types (each has a registered runtime handler)", "", "| Node | Produces | Side effects | Network | Risk | What it does |", "|---|---|---|---|---|---|"]
    for s in SPECS.values():
        L.append(f"| `{s.type}` | {s.out_type} | {s.side_effects.replace('_', ' ')} | {'yes' if s.network else 'no'} | {s.risk} | {s.description} |")
    L += ["", "Triggers: `manual`, `schedule` (5-field cron + IANA time zone), `event` (`new_finding`), `file`. `webhook` triggers are not implemented (the application runs no inbound listener).", "",
          "Error codes: " + ", ".join(f"`{c}`" for c in ERROR_CODES) + ".", "",
          "## Source adapters a workflow can use", "", "| Adapter | Class | Target types | Needs key | Default |", "|---|---|---|---|---|"]
    for a, ad in sorted(ads.items()):
        m = ad.manifest
        L.append(f"| `{a}` | {m.operation_class} | {', '.join(m.supported_target_types)} | {m.api_key_name or '—'} | {'on' if m.default_selected else 'explicit only'} |")
    L += ["", "## Template catalog (30)", "",
          "Maturity: **fixture-tested** = its dry run passes on synthetic fixture data in the test suite; **runtime-tested** = also executed end to end through the real engine and adapters (network mocked) in the suite. "
          "**No template is marked live-tested here**; see `docs/progress.md` for the live runs that were actually performed. Every template installs disabled.", "",
          "| ID | Name | Trigger | Needs | Optional | Maturity | Known gaps |", "|---|---|---|---|---|---|---|"]
    for t in catalog.load_all():
        gaps = "; ".join(t["capability_gaps"]) or "—"
        L.append(f"| {t['key']} | {t['name']} | {t['catalog_trigger']} | {', '.join(t['dependencies']) or 'local data'} | {', '.join(t['optional_dependencies']) or '—'} | {t['maturity'].replace('_', '-')} | {gaps} |")
    return "\n".join(L) + "\n"


def main(check: bool) -> int:
    text = build()
    if check:
        ok = OUT.exists() and OUT.read_text(encoding="utf8") == text
        print("current" if ok else "STALE: run scripts/gen_automation_docs.py")
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf8")
    print(f"wrote {OUT.name} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main("--check" in sys.argv))
