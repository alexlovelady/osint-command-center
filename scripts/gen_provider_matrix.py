"""Regenerate docs/provider-limit-matrix.md from the dispatcher's catalogue, so the documented limits cannot drift from the enforced ones.

    uv run python scripts/gen_provider_matrix.py
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from osintcc.quota.catalog import FIXED_DAY, FIXED_HOUR, FIXED_MINUTE, FIXED_MONTH, PROVIDERS, ROLLING

BASIS = {"documented": "published by the provider", "operator": "read from the operator's own account screen", "assumption": "conservative assumption (replaced by response headers)"}


def window_text(kind: str, seconds: int) -> str:
    return {FIXED_MINUTE: "per minute (resets on the minute, UTC)", FIXED_HOUR: "per hour (resets on the hour, UTC)", FIXED_DAY: "per day (resets 00:00 UTC)",
            FIXED_MONTH: "per month (resets on the 1st, 00:00 UTC; assumed)"}.get(kind, f"per rolling {seconds} s" if kind == ROLLING else kind)


def main() -> None:
    out = ["# Provider limit matrix", "",
           "Generated by `scripts/gen_provider_matrix.py` from `backend/osintcc/quota/catalog.py`: these are the limits the dispatcher enforces, not a copy of anyone's marketing page.", "",
           "Every figure is a **default**. Where a provider reports its own limits (urlscan.io, Brave, GitHub response headers; the urlscan.io quotas endpoint through Settings → Provider usage → Test) the provider's number replaces the default",
           "for that window. A 429, 401, 402 or 403 from the provider always overrides this table. No provider here was exercised live in this build: see [provider-quotas.md](provider-quotas.md) for what is fixture-tested.", "",
           "| Provider | Operation | Budget | Default limit | Basis | Other rules |", "|---|---|---|---:|---|---|"]
    for p in PROVIDERS.values():
        if p.disabled:
            out.append(f"| {p.label} | all | — | — | — | **{p.disabled}.** Never planned, never contacted. Re-enabling needs two explicit confirmations; it never buys anything. |")
            continue
        for op in p.ops.values():
            if op.blocked:
                out.append(f"| {p.label} | {op.label} | — | — | — | **Never dispatched.** {op.blocked} |")
                continue
            rules = []
            if op.concurrency:
                rules.append(f"{op.concurrency} request at a time")
            if op.min_spacing:
                rules.append(f"at least {op.min_spacing:g} s between requests")
            if op.cost != 1.0:
                rules.append(f"costs {op.cost:g} per request")
            for w in op.windows:
                unit = "credits" if w.unit == "credits" else "requests"
                out.append(f"| {p.label} | {op.label} | {window_text(w.kind, w.seconds)} | {w.limit:g} {unit} | {BASIS[w.basis]} | {'; '.join(rules)} |")
            if not op.windows:
                out.append(f"| {p.label} | {op.label} | no fixed budget | — | — | {'; '.join(rules)} |")
    out += ["", "## Reset rules and known limitations", ""]
    for p in PROVIDERS.values():
        out.append(f"### {p.label}")
        out.append(f"- Plan assumed: {p.plan}.")
        if p.credential:
            out.append(f"- Credential name in the credential store: `{p.credential}`.")
        if p.reset_note:
            out.append(f"- Resets: {p.reset_note}")
        for lim in p.limitations:
            out.append(f"- {lim}")
        if p.terms:
            out.append(f"- Terms/limits page: {p.terms}")
        out.append("")
    (ROOT / "docs" / "provider-limit-matrix.md").write_text("\n".join(out), encoding="utf-8")
    print("wrote docs/provider-limit-matrix.md")


if __name__ == "__main__":
    main()
